function rectPoly(u1: number, v1: number, u2: number, v2: number, fill: string): Poly2D {
  return {
    points: [
      { u: u1, v: v1 },
      { u: u2, v: v1 },
      { u: u2, v: v2 },
      { u: u1, v: v2 },
    ],
    fill,
  };
}

function rectEdges(u1: number, v1: number, u2: number, v2: number, dashed = false): Line2D[] {
  return [
    { from: { u: u1, v: v1 }, to: { u: u2, v: v1 }, dashed },
    { from: { u: u2, v: v1 }, to: { u: u2, v: v2 }, dashed },
    { from: { u: u2, v: v2 }, to: { u: u1, v: v2 }, dashed },
    { from: { u: u1, v: v2 }, to: { u: u1, v: v1 }, dashed },
  ];
}

function edge(u1: number, v1: number, u2: number, v2: number, dashed = false): Line2D {
  return { from: { u: u1, v: v1 }, to: { u: u2, v: v2 }, dashed };
}

